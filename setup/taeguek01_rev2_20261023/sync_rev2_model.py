#!/usr/bin/env python3
"""Generate K1 deployment XMLs inside the training Python environment.

Uses the resolved MJLab entity for physical overrides and upstream XML for full
precision body inertias. Torque motors are retained for the native PD runtime.
The output directory is a staging directory; review/verify before deployment.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import shutil
import sys
import xml.etree.ElementTree as ET


def numbers(value):
    import numpy as np
    return ' '.join(format(float(x), '.17g') for x in np.asarray(value).reshape(-1))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mjlab-root', required=True, type=Path)
    parser.add_argument('--world-template', required=True, type=Path)
    parser.add_argument('--output-dir', required=True, type=Path)
    args = parser.parse_args()
    sys.path.insert(0, str(args.mjlab_root.resolve()))
    import mujoco as mj
    from mjlab.entity import Entity
    from mjlab.terrains import TerrainEntity
    from source.assets.robots.robotis_k1.k1_rev2 import K1_REV2_XML_PATH
    from source.tasks.mimic.config.k1_rev2.taeguek01_env_cfg import k1_rev2_taeguek01_env_cfg

    cfg = k1_rev2_taeguek01_env_cfg(play=True)
    entity = Entity(cfg.scene.entities['robot'])
    robot = entity.spec.compile()
    terrain = TerrainEntity(cfg.scene.terrain, device='cpu').spec.compile()
    root = ET.parse(K1_REV2_XML_PATH).getroot()
    world = ET.parse(args.world_template).getroot()
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    mesh_source = (K1_REV2_XML_PATH.parent / root.find('compiler').get('meshdir')).resolve()
    mesh_dest = output / 'mjlab_assets_current'
    mesh_dest.mkdir(exist_ok=True)
    hashes = {}
    for mesh in root.findall('./asset/mesh'):
        filename = mesh.get('file')
        shutil.copy2(mesh_source / filename, mesh_dest / filename)
        hashes[filename] = hashlib.sha256((mesh_dest / filename).read_bytes()).hexdigest()
    root.find('compiler').set('meshdir', 'mjlab_assets_current/')
    root.insert(0, ET.Comment(' Generated by scripts/sync_k1_mjlab_model.py from cyclo_mjlab K1. '))
    root.insert(1, ET.Comment(' Robot physics follows MJLab; torque motors serve robotis_mujoco external PD. '))

    option = root.find('option')
    sim = cfg.sim.mujoco
    for key in ('timestep', 'impratio', 'iterations', 'tolerance', 'ls_iterations', 'ls_tolerance', 'ccd_iterations'):
        option.set(key, str(getattr(sim, key)))
    for key in ('integrator', 'cone', 'jacobian', 'solver'):
        value = getattr(sim, key)
        option.set(key, 'Newton' if value.lower() == 'newton' else value)
    option.set('gravity', numbers(sim.gravity))
    ET.SubElement(option, 'flag', multiccd='enable' if sim.multiccd else 'disable')

    # Keep the familiar world/camera appearance, while copying terrain physics.
    for tag in ('visual', 'statistic'):
        if world.find(tag) is not None:
            root.append(copy.deepcopy(world.find(tag)))
    for element in world.findall('./asset/texture') + world.findall('./asset/material'):
        if root.find(f"./asset/{element.tag}[@name='{element.get('name')}']") is None:
            root.find('asset').append(copy.deepcopy(element))
    for element in world.find('worldbody'):
        if element.tag in ('light', 'camera'):
            root.find('worldbody').append(copy.deepcopy(element))
    floor = copy.deepcopy(world.find("./worldbody/geom[@name='floor']"))
    floor.set('contype', str(int(terrain.geom_contype[0])))
    floor.set('conaffinity', str(int(terrain.geom_conaffinity[0])))
    for field in ('condim', 'priority', 'friction', 'solref', 'solimp', 'solmix', 'margin', 'gap'):
        floor.set(field, numbers(getattr(terrain, 'geom_' + field)[0]))
    root.find('worldbody').insert(0, floor)

    for g in root.findall('.//body/geom'):
        name = g.get('name', '')
        if not name:
            continue
        idx = mj.mj_name2id(robot, mj.mjtObj.mjOBJ_GEOM, name)
        if idx < 0:
            raise ValueError(f'Geometry missing from resolved MJLab entity: {name}')
        for field in ('contype', 'conaffinity', 'condim', 'priority', 'friction', 'solref', 'solimp', 'solmix', 'margin', 'gap'):
            g.set(field, numbers(getattr(robot, 'geom_' + field)[idx]))
    # Viewer controls use group 1 for visual meshes; physical fields are unchanged.
    root.find("./default/default[@class='visual']/geom").set('group', '1')
    for joint in root.findall('.//body/joint'):
        idx = mj.mj_name2id(robot, mj.mjtObj.mjOBJ_JOINT, joint.get('name'))
        dof = robot.jnt_dofadr[idx]
        for field in ('armature', 'damping', 'frictionloss'):
            joint.set(field, numbers(getattr(robot, 'dof_' + field)[dof]))

    runtime = ET.fromstring(entity.spec.to_xml())
    for side in ('left', 'right'):
        site = runtime.find(f".//site[@name='{side}_foot']")
        root.find(f".//body[@name='{side}_ankle_roll_link']").append(copy.deepcopy(site))
    for sensor in runtime.find('sensor'):
        if root.find(f"./sensor/*[@name='{sensor.get('name')}']") is None:
            root.find('sensor').append(copy.deepcopy(sensor))

    # Soft presets are explicit overrides of only the 18 foot-floor contacts.
    feet = [g.get('name') for g in root.findall('.//body/geom')
            if '_ankle_roll_link_collision_' in g.get('name', '')]
    if len(feet) != 18:
        raise ValueError(f'Expected 18 K1 foot spheres, got {len(feet)}')
    for variant, timeconst in [('', None), ('_soft_A', .02), ('_soft_B', .04), ('_soft_C', .06)]:
        tree = copy.deepcopy(root)
        if timeconst is not None:
            contact = tree.find('contact')
            if contact is None:
                contact = ET.SubElement(tree, 'contact')
            for name in feet:
                idx = mj.mj_name2id(robot, mj.mjtObj.mjOBJ_GEOM, name)
                mu = robot.geom_friction[idx]
                ET.SubElement(contact, 'pair', geom1='floor', geom2=name, condim='3',
                              friction=numbers([mu[0], mu[0], mu[1], mu[2], mu[2]]),
                              solref=numbers([timeconst, 1]), solimp=numbers(robot.geom_solimp[idx]))
        ET.indent(tree, space='  ')
        ET.ElementTree(tree).write(output / f'k1_mjlab{variant}.xml', encoding='unicode')

    def snapshot(kind, count, fields):
        return {mj.mj_id2name(robot, kind, i): {f: getattr(robot, f)[i].tolist() for f in fields}
                for i in range(count) if mj.mj_id2name(robot, kind, i)}
    reference = {
        'mujoco_version': mj.__version__, 'xml_sha256': hashlib.sha256(K1_REV2_XML_PATH.read_bytes()).hexdigest(),
        'mesh_sha256': hashes,
        'body': snapshot(mj.mjtObj.mjOBJ_BODY, robot.nbody, ['body_mass','body_pos','body_quat','body_ipos','body_iquat','body_inertia']),
        'joint': snapshot(mj.mjtObj.mjOBJ_JOINT, robot.njnt, ['jnt_type','jnt_pos','jnt_axis','jnt_range','jnt_limited','jnt_actfrcrange']),
        'geom': snapshot(mj.mjtObj.mjOBJ_GEOM, robot.ngeom, ['geom_type','geom_pos','geom_quat','geom_size','geom_contype','geom_conaffinity','geom_condim','geom_priority','geom_friction','geom_solref','geom_solimp','geom_margin','geom_gap']),
        'dof_armature': robot.dof_armature.tolist(), 'dof_damping': robot.dof_damping.tolist(),
        'dof_frictionloss': robot.dof_frictionloss.tolist(),
        'floor': {f: getattr(terrain, 'geom_'+f)[0].tolist() for f in ['contype','conaffinity','condim','friction','solref','solimp']},
    }
    (output / 'mjlab_physics_reference.json').write_text(json.dumps(reference, indent=2)+'\n')
    for path in output.glob('*.xml'):
        mj.MjModel.from_xml_path(str(path))
    print(f'Generated 4 XMLs, {len(feet)} foot spheres, mass={robot.body_mass.sum():.8f} kg in {output}')


if __name__ == '__main__':
    main()
